"""Collect the summary.md of every exploration step into one report.

Image links in each summary are relative to its own folder; they are
rewritten to be relative to the report.
"""

import argparse
import re
from pathlib import Path

HEADER = """# Weekday timetable exploration

Generated by `snakemake explore` from `{schedule}`. Each section comes from one
`explore_*` script; its folder next to this file has the full tables (CSV) and
figures. Times are minutes or HH:MM of the service day (after midnight is 24:xx).
"""


def main(sections, schedule, out):
    out = Path(out)
    parts = [HEADER.format(schedule=schedule)]
    for s in sections:
        s = Path(s)
        rel = s.parent.relative_to(out.parent).as_posix()
        text = s.read_text(encoding="utf-8")
        parts.append(re.sub(r"!\[([^\]]*)\]\((?!https?:)([^)]+)\)", rf"![\1]({rel}/\2)", text))
    out.write_text("\n".join(parts), encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--schedule", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("sections", nargs="+")
    args = parser.parse_args()
    main(args.sections, args.schedule, args.out)
